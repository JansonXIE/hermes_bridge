"""Server-side configuration. Task requests can only select from what is declared here."""

from __future__ import annotations

import os
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

DEFAULT_ENV_PASSTHROUGH = [
    "PATH", "HOME", "USER", "LOGNAME", "SHELL", "LANG", "LC_*", "TZ", "TERM",
    "ANTHROPIC_*", "CLAUDE_CODE_*", "CLAUDE_CONFIG_DIR",
    "HTTP_PROXY", "HTTPS_PROXY", "NO_PROXY", "http_proxy", "https_proxy", "no_proxy",
    "SSL_CERT_FILE", "SSL_CERT_DIR", "NODE_EXTRA_CA_CERTS",
]
# Inherited from a parent Claude Code session; would confuse a fresh headless run.
NESTED_SESSION_ENV = {
    "CLAUDECODE", "CLAUDE_CODE_SESSION_ID", "CLAUDE_CODE_CHILD_SESSION",
    "CLAUDE_CODE_ENTRYPOINT", "CLAUDE_CODE_EXECPATH",
}
DEFAULT_SYSTEM_PROMPT = (
    "You are a worker dispatched by an orchestrator, running non-interactively in an isolated "
    "working directory. Stay inside it. Do not bypass git hooks. When finished, report what you "
    "changed and the exact test commands you ran with their outcomes. If you could not verify "
    "something, say so."
)
# Satisfies the commit-msg hook deployed on the target machines; override per project if needed.
DEFAULT_COMMIT_MESSAGE = """[chore](bridge): {action} for {task_id}

[description ]:{action}, generated by hermes-bridge for task {task_id}
[root   cause]:NA
[JIRA      ID]:NA
[chip project]:NA
[side effects]:NA
[Affected *.ko/*.so/*.a] :NA
"""


INPLACE_ALLOWED_TOOLS = ("Read", "Glob", "Grep")
INPLACE_DENIED_TOOLS = ("Edit", "Write", "NotebookEdit", "Bash")


class ConfigError(Exception):
    pass


@dataclass(frozen=True)
class Principal:
    name: str
    token: str
    projects: frozenset[str]

    def can_access(self, project_id: str) -> bool:
        return "*" in self.projects or project_id in self.projects


@dataclass(frozen=True)
class Project:
    id: str
    path: Optional[Path]
    isolation: str = "worktree"
    base_ref: str = "HEAD"
    permission_mode: str = "dontAsk"
    allowed_tools: tuple[str, ...] = ()
    disallowed_tools: tuple[str, ...] = ()
    model: Optional[str] = None
    effort: Optional[str] = None
    max_budget_usd: Optional[float] = None
    verify_command: tuple[str, ...] = ()
    verify_timeout_seconds: int = 900
    auto_commit: bool = True
    commit_message: str = DEFAULT_COMMIT_MESSAGE
    env: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class Config:
    data_dir: Path
    api_host: str
    api_port: int
    principals: tuple[Principal, ...]
    projects: dict[str, Project]
    max_concurrency: int = 3
    lease_seconds: float = 30.0
    poll_seconds: float = 0.5
    tick_seconds: float = 0.3
    term_grace_seconds: float = 10.0
    kill_wait_seconds: float = 5.0
    default_timeout_seconds: int = 1800
    max_timeout_seconds: int = 14400
    max_attempts: int = 2
    silence_alert_seconds: float = 600.0
    event_retention_days: float = 14.0
    port_base: int = 21000
    port_block: int = 100
    claude_command: tuple[str, ...] = ("claude",)
    claude_extra_args: tuple[str, ...] = ()
    include_partial_messages: bool = True
    append_system_prompt: str = DEFAULT_SYSTEM_PROMPT
    env_passthrough: tuple[str, ...] = tuple(DEFAULT_ENV_PASSTHROUGH)
    notify_url: Optional[str] = None
    notify_secret: Optional[str] = None
    notify_max_attempts: int = 12
    notify_base_backoff: float = 2.0
    notify_max_backoff: float = 300.0
    adapter_host: str = "127.0.0.1"
    adapter_port: int = 8766
    adapter_token: Optional[str] = None
    adapter_coalesce_seconds: float = 3.0
    adapter_lease_seconds: float = 60.0
    adapter_max_attempts: int = 10
    adapter_fallback_command: tuple[str, ...] = ()
    adapter_fallback_after_seconds: float = 120.0
    adapter_fallback_timeout_seconds: float = 900.0

    @property
    def db_path(self) -> Path:
        return self.data_dir / "bridge.db"

    @property
    def adapter_db_path(self) -> Path:
        return self.data_dir / "adapter.db"

    @property
    def workspaces_dir(self) -> Path:
        return self.data_dir / "workspaces"

    @property
    def runs_dir(self) -> Path:
        return self.data_dir / "runs"

    @property
    def locks_dir(self) -> Path:
        return self.data_dir / "locks"

    def secrets(self) -> list[str]:
        values = [p.token for p in self.principals]
        values += [self.notify_secret or "", self.adapter_token or ""]
        return [v for v in values if v]


def _secret(section: dict, key: str, where: str) -> Optional[str]:
    env_name = section.get(f"{key}_env")
    if env_name:
        value = os.environ.get(env_name)
        if not value:
            raise ConfigError(f"{where}: environment variable {env_name} is not set")
        return value
    return section.get(key)


def _project(project_id: str, raw: dict, base: Path) -> Project:
    where = f"projects.{project_id}"
    isolation = raw.get("isolation", "worktree")
    if isolation not in ("worktree", "directory", "inplace"):
        raise ConfigError(f"{where}: isolation must be 'worktree', 'directory' or 'inplace'")
    path = None
    if isolation in ("worktree", "inplace"):
        if "path" not in raw:
            raise ConfigError(f"{where}: path is required for {isolation} isolation")
        path = (base / raw["path"]).resolve()
    mode = raw.get("permission_mode", "dontAsk")
    if mode == "bypassPermissions" and raw.get("allow_bypass_permissions") is not True:
        raise ConfigError(
            f"{where}: bypassPermissions requires allow_bypass_permissions = true and a real sandbox"
        )
    disallowed = tuple(raw.get("disallowed_tools", ()))
    if isolation == "inplace":
        # Claude runs in the live checkout, shared by all tasks: reading only.
        if mode != "dontAsk":
            raise ConfigError(f"{where}: inplace isolation requires permission_mode = 'dontAsk'")
        extra = set(raw.get("allowed_tools", ())) - set(INPLACE_ALLOWED_TOOLS)
        if extra:
            raise ConfigError(f"{where}: inplace isolation only allows {list(INPLACE_ALLOWED_TOOLS)}, not {sorted(extra)}")
        if raw.get("verify_command"):
            raise ConfigError(f"{where}: inplace isolation cannot run a verify_command")
        # Deny rules also override allow rules from the user's own Claude settings.
        disallowed += tuple(t for t in INPLACE_DENIED_TOOLS if t not in disallowed)
    return Project(
        id=project_id,
        path=path,
        isolation=isolation,
        base_ref=raw.get("base_ref", "HEAD"),
        permission_mode=mode,
        allowed_tools=tuple(raw.get("allowed_tools", ())),
        disallowed_tools=disallowed,
        model=raw.get("model"),
        effort=raw.get("effort"),
        max_budget_usd=raw.get("max_budget_usd"),
        verify_command=tuple(raw.get("verify_command", ())),
        verify_timeout_seconds=int(raw.get("verify_timeout_seconds", 900)),
        auto_commit=bool(raw.get("auto_commit", True)),
        commit_message=raw.get("commit_message", DEFAULT_COMMIT_MESSAGE),
        env=dict(raw.get("env", {})),
    )


def load_config(path: str | Path) -> Config:
    path = Path(path).resolve()
    with open(path, "rb") as f:
        raw = tomllib.load(f)
    base = path.parent

    api = raw.get("api", {})
    principals = []
    for i, entry in enumerate(api.get("tokens", ())):
        where = f"api.tokens[{i}]"
        token = _secret(entry, "token", where)
        if not token or len(token) < 16:
            raise ConfigError(f"{where}: token must be at least 16 characters")
        principals.append(
            Principal(name=entry["name"], token=token, projects=frozenset(entry.get("projects", ())))
        )
    if not principals:
        raise ConfigError("api.tokens: at least one token is required, every endpoint is authenticated")

    for pid, conf in raw.get("projects", {}).items():
        nested = [k for k, v in conf.items() if isinstance(v, dict) and k != "env"]
        if nested and "path" not in conf:
            raise ConfigError(f'projects.{pid}: a dot in an id must be quoted, e.g. [projects."{pid}.{nested[0]}"]')
    projects = {pid: _project(pid, conf, base) for pid, conf in raw.get("projects", {}).items()}
    worker = raw.get("worker", {})
    claude = raw.get("claude", {})
    notify = raw.get("notify", {})
    adapter = raw.get("adapter", {})

    numeric = {
        k: worker[k]
        for k in (
            "max_concurrency", "lease_seconds", "poll_seconds", "tick_seconds", "term_grace_seconds",
            "kill_wait_seconds", "default_timeout_seconds", "max_timeout_seconds", "max_attempts",
            "silence_alert_seconds", "event_retention_days", "port_base", "port_block",
        )
        if k in worker
    }
    if numeric.get("max_concurrency", 3) < 1:
        raise ConfigError("worker.max_concurrency must be at least 1")

    optional = {}
    if "append_system_prompt" in claude:
        optional["append_system_prompt"] = claude["append_system_prompt"]
    for src, dst in (
        ("max_attempts", "notify_max_attempts"),
        ("base_backoff", "notify_base_backoff"),
        ("max_backoff", "notify_max_backoff"),
    ):
        if src in notify:
            optional[dst] = notify[src]
    for src, dst in (
        ("coalesce_seconds", "adapter_coalesce_seconds"),
        ("lease_seconds", "adapter_lease_seconds"),
        ("max_attempts", "adapter_max_attempts"),
        ("fallback_after_seconds", "adapter_fallback_after_seconds"),
        ("fallback_timeout_seconds", "adapter_fallback_timeout_seconds"),
    ):
        if src in adapter:
            optional[dst] = adapter[src]

    return Config(
        data_dir=(base / raw.get("data_dir", "data")).resolve(),
        api_host=api.get("host", "127.0.0.1"),
        api_port=int(api.get("port", 8765)),
        principals=tuple(principals),
        projects=projects,
        claude_command=tuple(claude.get("command", ("claude",))),
        claude_extra_args=tuple(claude.get("extra_args", ())),
        include_partial_messages=bool(claude.get("include_partial_messages", True)),
        env_passthrough=tuple(claude.get("env_passthrough", DEFAULT_ENV_PASSTHROUGH)),
        notify_url=notify.get("url"),
        notify_secret=_secret(notify, "secret", "notify"),
        adapter_host=adapter.get("host", "127.0.0.1"),
        adapter_port=int(adapter.get("port", 8766)),
        adapter_token=_secret(adapter, "token", "adapter"),
        adapter_fallback_command=tuple(adapter.get("fallback_command", ())),
        **numeric,
        **optional,
    )
